"""Query embedding and source-aware vector retrieval orchestration."""

from typing import Protocol

from app.services.chunking import TextChunk
from app.services.embeddings import EmbeddingError, EmbeddingService
from app.services.vector_store import ScoredChunk, VectorStore


class RetrievalError(Exception):
    """Base error for safe retrieval failures."""


class EmbeddingUnavailableError(RetrievalError):
    """The configured query embedding provider could not produce a vector."""


class VectorStoreError(RetrievalError):
    """The vector store could not count or search indexed chunks."""


class VectorRetriever(Protocol):
    """Legacy search contract retained for existing RAG integrations."""

    async def search(self, vector: list[float], limit: int) -> list[TextChunk]:
        """Return source chunks for a query vector."""
        ...


class RetrievalService:
    """Embed a query and retrieve pre-indexed chunks without re-embedding them."""

    def __init__(self, embeddings: EmbeddingService, vector_store: VectorStore) -> None:
        self.embeddings = embeddings
        self.vector_store = vector_store

    async def retrieve(
        self,
        query: str,
        *,
        limit: int = 5,
        course_id: str | None = None,
        document_id: str | None = None,
    ) -> list[ScoredChunk]:
        """Return most relevant indexed chunks, preserving their source metadata.

        Empty queries, nonpositive limits, and filters with no indexed chunks
        return an empty result. Only query text is embedded; document vectors
        remain in the vector store and are never regenerated by retrieval.
        """
        normalized_query = query.strip()
        if not normalized_query or limit <= 0:
            return []
        try:
            count = await self.vector_store.count(course_id=course_id, document_id=document_id)
        except Exception as exc:
            raise VectorStoreError("Vector store is unavailable.") from exc
        if count == 0:
            return []

        try:
            query_vector = await self.embeddings.embed_query(normalized_query)
        except EmbeddingError as exc:
            raise EmbeddingUnavailableError("Query embeddings are unavailable.") from exc

        try:
            results = await self.vector_store.search(
                query_vector,
                limit=limit,
                embedding_model=self.embeddings.model_id,
                course_id=course_id,
                document_id=document_id,
            )
        except Exception as exc:
            raise VectorStoreError("Vector search failed.") from exc
        if self.embeddings.is_mock:
            return [result.model_copy(update={"is_mock_embedding": True}) for result in results]
        return results
